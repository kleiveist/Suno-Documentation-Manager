fn push_documented_row(rows: &mut Vec<TableRow>, label: &str, value: &str, mono: bool) {
    if value.trim().is_empty() {
        return;
    }
    rows.push(if mono {
        TableRow::mono(label, value)
    } else {
        TableRow::plain(label, value)
    });
}

