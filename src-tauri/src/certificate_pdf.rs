fn evidence_digest<'a>(evidence: &'a [&'a EvidenceItem], role: EvidenceRole) -> Option<&'a str> {
    evidence
        .iter()
        .find(|item| item.role == role)
        .and_then(|item| item.sha256.as_deref())
}

fn documented(value: &str) -> &str {
    if value.trim().is_empty() {
        "Not documented"
    } else {
        value
    }
}

