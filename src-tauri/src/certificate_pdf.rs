/// The immutable, finalized data used to render a documentation certificate PDF.
///
/// `steps` is authoritative and is rendered in exactly the supplied order. `evidence` must be
/// the already filtered and `relative_path`-sorted slice used for the finalized evidence
/// manifest. The renderer validates those invariants but deliberately does not re-evaluate,
/// filter, or sort either slice.
pub struct CertificatePdfSnapshot<'a> {
    pub track: &'a TrackRecord,
    pub automation: &'a TrackAutomation,
    pub profile: &'a Profile,
    pub steps: &'a [StepState],
    pub evidence: &'a [&'a EvidenceItem],
    pub deviations: &'a [BlockingDeviation],
    pub revision_references: &'a [String],
    pub certificate_id: &'a str,
    pub finalized_at: &'a str,
    pub certificate_version: &'a str,
    pub sha256sums_sha256: &'a str,
    pub evidence_manifest_sha256: &'a str,
    pub markdown_certificate_sha256: &'a str,
}

/// Render an A4, multi-page technical certificate from a finalized snapshot.
pub fn generate_pdf(snapshot: &CertificatePdfSnapshot<'_>) -> Result<Vec<u8>> {
    let workflow_config = validate_snapshot(snapshot)?;
    let step_labels = workflow_config
        .steps
        .iter()
        .map(|step| (step.id.as_str(), step.name.as_str()))
        .collect::<HashMap<_, _>>();

    let mut layout = PdfLayout::new();
    render_document_title(&mut layout);
    render_header_metadata(&mut layout, snapshot);
    render_track_data(&mut layout, snapshot);
    render_final_suno_generation(&mut layout, snapshot);
    render_sources_and_generation(&mut layout, snapshot);
    render_human_contribution(&mut layout, snapshot);
    render_ai_usage(&mut layout, snapshot);
    render_artwork_checks(&mut layout, snapshot);
    render_license_and_rights(&mut layout, snapshot);
    render_evidence_register(&mut layout, snapshot.evidence);
    render_integrity_anchors(&mut layout, snapshot);
    render_workflow(&mut layout, snapshot.steps, &step_labels);
    render_certificate_statement(&mut layout, snapshot);

    let pages = layout.into_pages(snapshot.certificate_id);
    let mut document = PdfDocument::new(DOCUMENT_TITLE);
    document.metadata.info.author = snapshot.profile.artist_name.clone();
    document.metadata.info.creator = GENERATED_BY.to_owned();
    document.metadata.info.producer = GENERATED_BY.to_owned();
    document.metadata.info.subject =
        "Finalized technical documentation, evidence, and integrity snapshot".to_owned();
    document.metadata.info.identifier = snapshot.certificate_id.to_owned();
    document.metadata.info.keywords = vec![
        "SunoDM".to_owned(),
        "documentation".to_owned(),
        "evidence".to_owned(),
        "SHA-256".to_owned(),
    ];
    document.with_pages(pages);

    let mut warnings = Vec::new();
    let mut bytes = document.save(&PdfSaveOptions::default(), &mut warnings);
    if let Some(warning) = warnings
        .iter()
        .find(|warning| warning.severity == PdfParseErrorSeverity::Error)
    {
        return Err(AppError::Data(format!(
            "Certificate PDF serialization failed: {}",
            warning.msg
        )));
    }
    make_pdf_trailer_id_deterministic(&mut bytes, snapshot.certificate_id)?;
    validate_pdf_bytes(&bytes)?;
    Ok(bytes)
}

fn make_pdf_trailer_id_deterministic(bytes: &mut [u8], certificate_id: &str) -> Result<()> {
    const PREFIX: &[u8] = b"/ID[(";
    const SEPARATOR: &[u8] = b")(";
    const SUFFIX: &[u8] = b")]";
    const ID_LEN: usize = 32;

    let prefix = bytes
        .windows(PREFIX.len())
        .rposition(|window| window == PREFIX)
        .ok_or_else(|| AppError::Data("Certificate PDF trailer has no document ID.".into()))?;
    let first = prefix + PREFIX.len();
    let separator = first + ID_LEN;
    let second = separator + SEPARATOR.len();
    let suffix = second + ID_LEN;
    if bytes.get(separator..second) != Some(SEPARATOR)
        || bytes.get(suffix..suffix + SUFFIX.len()) != Some(SUFFIX)
    {
        return Err(AppError::Data(
            "Certificate PDF trailer has an unexpected document ID format.".into(),
        ));
    }

    let digest = crate::security::sha256_bytes(certificate_id.as_bytes());
    bytes[first..separator].copy_from_slice(&digest.as_bytes()[..ID_LEN]);
    bytes[second..suffix].copy_from_slice(&digest.as_bytes()[ID_LEN..]);
    Ok(())
}

/// Parse staged PDF bytes and reject malformed or empty documents before publication.
pub fn validate_pdf_bytes(bytes: &[u8]) -> Result<()> {
    if !bytes.starts_with(b"%PDF-") {
        return Err(AppError::Validation(
            "Generated certificate PDF has no valid PDF header.".into(),
        ));
    }

    let mut warnings = Vec::new();
    let document =
        PdfDocument::parse(bytes, &PdfParseOptions::default(), &mut warnings).map_err(|error| {
            AppError::Validation(format!(
                "Generated certificate PDF cannot be parsed: {error}"
            ))
        })?;
    if document.pages.is_empty() {
        return Err(AppError::Validation(
            "Generated certificate PDF contains no pages.".into(),
        ));
    }
    if let Some(warning) = warnings
        .iter()
        .find(|warning| warning.severity == PdfParseErrorSeverity::Error)
    {
        return Err(AppError::Validation(format!(
            "Generated certificate PDF contains an invalid operation: {}",
            warning.msg
        )));
    }
    Ok(())
}

fn validate_snapshot(snapshot: &CertificatePdfSnapshot<'_>) -> Result<workflow::WorkflowConfig> {
    for (label, value) in [
        ("certificate ID", snapshot.certificate_id),
        ("finalization timestamp", snapshot.finalized_at),
        ("certificate version", snapshot.certificate_version),
    ] {
        if value.trim().is_empty() {
            return Err(AppError::Data(format!(
                "Certificate PDF snapshot has no {label}."
            )));
        }
    }
    for (label, digest) in [
        ("SHA256SUMS.txt", snapshot.sha256sums_sha256),
        ("EVIDENCE_MANIFEST.json", snapshot.evidence_manifest_sha256),
        (
            "DOCUMENTATION_CERTIFICATE.md",
            snapshot.markdown_certificate_sha256,
        ),
    ] {
        validate_sha256(label, digest)?;
    }

    if snapshot
        .evidence
        .windows(2)
        .any(|items| items[0].relative_path > items[1].relative_path)
    {
        return Err(AppError::Data(
            "Certificate PDF evidence is not sorted by relative path.".into(),
        ));
    }
    for item in snapshot.evidence {
        if !item.verified || item.verification_error.is_some() {
            return Err(AppError::Data(format!(
                "Certificate PDF evidence is not verified: {}",
                item.relative_path
            )));
        }
        let digest = item.sha256.as_deref().ok_or_else(|| {
            AppError::Data(format!(
                "Certificate PDF evidence has no SHA-256: {}",
                item.relative_path
            ))
        })?;
        validate_sha256(&item.relative_path, digest)?;
    }

    let config = workflow::config()?;
    if snapshot.track.workflow_id != config.id || snapshot.track.workflow_version != config.version
    {
        return Err(AppError::Data(
            "Certificate PDF workflow metadata does not match the configured workflow.".into(),
        ));
    }
    let configured_ids = config
        .steps
        .iter()
        .map(|step| step.id.as_str())
        .collect::<HashSet<_>>();
    let mut supplied_ids = HashSet::new();
    for step in snapshot.steps {
        if !configured_ids.contains(step.id.as_str()) {
            return Err(AppError::Data(format!(
                "Certificate PDF contains an unknown workflow step: {}",
                step.id
            )));
        }
        if !supplied_ids.insert(step.id.as_str()) {
            return Err(AppError::Data(format!(
                "Certificate PDF contains a duplicate workflow step: {}",
                step.id
            )));
        }
        match step.status {
            StepStatus::Pass => {}
            StepStatus::NotApplicable => {
                if step
                    .na_reason
                    .as_deref()
                    .is_none_or(|reason| reason.trim().is_empty())
                {
                    return Err(AppError::Data(format!(
                        "Certificate PDF workflow step has no N/A reason: {}",
                        step.id
                    )));
                }
            }
            _ => {
                return Err(AppError::Validation(format!(
                    "Certificate PDF workflow step is not complete: {} ({})",
                    step.id,
                    step_status(&step.status)
                )));
            }
        }
    }
    if supplied_ids.len() != configured_ids.len() {
        return Err(AppError::Data(
            "Certificate PDF workflow snapshot is incomplete.".into(),
        ));
    }
    if snapshot
        .deviations
        .iter()
        .any(|deviation| deviation.blocking && !deviation.resolved)
    {
        return Err(AppError::Validation(
            "Certificate PDF snapshot contains an open blocking deviation.".into(),
        ));
    }
    validate_rendered_text(snapshot, &config)?;
    Ok(config)
}

fn validate_sha256(label: &str, digest: &str) -> Result<()> {
    if digest.len() != 64 || !digest.bytes().all(|byte| byte.is_ascii_hexdigit()) {
        return Err(AppError::Data(format!(
            "Certificate PDF has an invalid SHA-256 for {label}."
        )));
    }
    Ok(())
}

