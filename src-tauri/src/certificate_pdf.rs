struct PdfLayout {
    pages: Vec<Vec<Op>>,
    y_mm: f32,
    render_options: CertificateRenderOptions,
}

impl PdfLayout {
    fn new(render_options: CertificateRenderOptions) -> Self {
        Self {
            pages: vec![Vec::new()],
            y_mm: FIRST_PAGE_TOP_MM,
            render_options,
        }
    }

    fn label(&self, english: &str) -> String {
        localized_certificate_label(self.render_options, english)
    }

    fn paragraph(&self, english: &str) -> String {
        localized_certificate_paragraph(self.render_options, english)
    }

    fn write_localized(
        &mut self,
        english: &str,
        x_mm: f32,
        width_mm: f32,
        size_pt: f32,
        font: BuiltinFont,
        line_factor: f32,
    ) {
        let text = self.paragraph(english);
        self.write_wrapped(&text, x_mm, width_mm, size_pt, font, line_factor);
    }

    fn current_ops(&mut self) -> &mut Vec<Op> {
        self.pages
            .last_mut()
            .expect("PDF layout always contains a page")
    }

    fn fits(&self, height_mm: f32) -> bool {
        self.y_mm - height_mm >= CONTENT_BOTTOM_MM
    }

    fn full_content_height(&self) -> f32 {
        CONTINUATION_TOP_MM - CONTENT_BOTTOM_MM
    }

    fn ensure_space(&mut self, height_mm: f32) {
        if !self.fits(height_mm) {
            self.new_page();
        }
    }

    fn new_page(&mut self) {
        self.pages.push(Vec::new());
        self.y_mm = CONTINUATION_TOP_MM;
        let title = self.label(DOCUMENT_TITLE);
        self.text_at(LEFT_MM, 285.0, &title, 6.8, BuiltinFont::HelveticaBold);
        self.rule(LEFT_MM, RIGHT_MM, 281.5, 0.35);
    }

    fn continuation_title(&mut self, title: &str) {
        self.ensure_space(8.0);
        let title = self.label(title);
        self.text_at(
            LEFT_MM,
            self.y_mm - 3.2,
            &title,
            9.5,
            BuiltinFont::HelveticaBold,
        );
        self.y_mm -= 6.5;
        self.rule(LEFT_MM, RIGHT_MM, self.y_mm, 0.5);
        self.y_mm -= 1.5;
    }

    fn section_title(&mut self, title: &str) {
        self.ensure_space(13.0);
        self.y_mm -= 2.0;
        let title = self.label(title);
        self.text_at(
            LEFT_MM,
            self.y_mm - 3.5,
            &title,
            10.0,
            BuiltinFont::HelveticaBold,
        );
        self.y_mm -= 7.0;
        self.rule(LEFT_MM, RIGHT_MM, self.y_mm, 0.5);
        self.y_mm -= 1.5;
    }

    fn write_wrapped(
        &mut self,
        text: &str,
        x_mm: f32,
        width_mm: f32,
        size_pt: f32,
        font: BuiltinFont,
        line_factor: f32,
    ) {
        let lines = wrap_text(text, width_mm, size_pt, font);
        let line_height_mm = size_pt * 0.352_778 * line_factor;
        for line in lines {
            self.ensure_space(line_height_mm);
            let baseline = self.y_mm - size_pt * 0.352_778 * 0.82;
            self.text_at(x_mm, baseline, &line, size_pt, font);
            self.y_mm -= line_height_mm;
        }
    }

    fn table_rows(&mut self, rows: &[TableRow], label_width_mm: f32) {
        for row in rows {
            self.table_row(row, label_width_mm);
        }
    }

    fn table_row(&mut self, row: &TableRow, label_width_mm: f32) {
        let label_x = LEFT_MM + 1.0;
        let value_x = LEFT_MM + label_width_mm + 2.0;
        let value_width = RIGHT_MM - value_x - 1.0;
        let label = self.label(&row.label);
        let label_lines = wrap_text(
            &label,
            label_width_mm - 2.0,
            6.7,
            BuiltinFont::HelveticaBold,
        );
        let value_lines = wrap_text(&row.value, value_width, row.value_size_pt, row.value_font);
        let line_count = label_lines.len().max(value_lines.len()).max(1);
        let line_height_mm = 3.35;
        let total_height = line_count as f32 * line_height_mm + 2.0;
        if total_height <= self.full_content_height() && !self.fits(total_height) {
            self.new_page();
        }

        self.y_mm -= 0.8;
        for line_index in 0..line_count {
            let continued = if !self.fits(line_height_mm + 0.8) {
                self.new_page();
                let continuation_label = self.label(&format!("{} (continuation)", row.label));
                self.text_at(
                    label_x,
                    self.y_mm - 2.45,
                    &continuation_label,
                    6.7,
                    BuiltinFont::HelveticaBold,
                );
                true
            } else {
                false
            };
            let baseline = self.y_mm - 2.45;
            if !continued {
                if let Some(line) = label_lines.get(line_index) {
                    self.text_at(label_x, baseline, line, 6.7, BuiltinFont::HelveticaBold);
                }
            }
            if let Some(line) = value_lines.get(line_index) {
                self.text_at(value_x, baseline, line, row.value_size_pt, row.value_font);
            }
            self.y_mm -= line_height_mm;
        }
        self.y_mm -= 0.4;
        self.rule(LEFT_MM, RIGHT_MM, self.y_mm, 0.2);
        self.y_mm -= 0.8;
    }

    fn column_heading(&mut self, left: &str, right: &str, label_width_mm: f32) {
        self.ensure_space(6.0);
        let y = self.y_mm - 2.5;
        let left = self.label(left);
        let right = self.label(right);
        self.text_at(LEFT_MM + 1.0, y, &left, 6.5, BuiltinFont::HelveticaBold);
        self.text_at(
            LEFT_MM + label_width_mm + 2.0,
            y,
            &right,
            6.5,
            BuiltinFont::HelveticaBold,
        );
        self.y_mm -= 4.0;
        self.rule(LEFT_MM, RIGHT_MM, self.y_mm, 0.45);
        self.y_mm -= 1.0;
    }

    fn evidence_summary_row(
        &mut self,
        index: usize,
        role: &str,
        provenance: &str,
        size_bytes: u64,
    ) {
        self.ensure_space(6.0);
        let y = self.y_mm - 2.5;
        self.text_at(
            LEFT_MM + 1.0,
            y,
            &index.to_string(),
            6.4,
            BuiltinFont::CourierBold,
        );
        self.text_at(LEFT_MM + 12.0, y, role, 6.4, BuiltinFont::Courier);
        self.text_at(LEFT_MM + 77.0, y, provenance, 6.4, BuiltinFont::Courier);
        self.text_at(
            LEFT_MM + 130.0,
            y,
            &size_bytes.to_string(),
            6.4,
            BuiltinFont::Courier,
        );
        self.y_mm -= 4.0;
        self.rule(LEFT_MM, RIGHT_MM, self.y_mm, 0.25);
        self.y_mm -= 0.7;
    }

    fn text_at(&mut self, x_mm: f32, y_mm: f32, text: &str, size_pt: f32, font: BuiltinFont) {
        self.current_ops().extend([
            Op::StartTextSection,
            Op::SetTextCursor {
                pos: Point::new(Mm(x_mm), Mm(y_mm)),
            },
            Op::SetFont {
                font: PdfFontHandle::Builtin(font),
                size: Pt(size_pt),
            },
            Op::ShowText {
                items: vec![TextItem::Text(text.to_owned())],
            },
            Op::EndTextSection,
        ]);
    }

    fn rule(&mut self, from_x_mm: f32, to_x_mm: f32, y_mm: f32, thickness_pt: f32) {
        self.current_ops().extend([
            Op::SaveGraphicsState,
            Op::SetOutlineColor {
                col: Color::Rgb(Rgb {
                    r: 0.48,
                    g: 0.48,
                    b: 0.48,
                    icc_profile: None,
                }),
            },
            Op::SetOutlineThickness {
                pt: Pt(thickness_pt),
            },
            Op::DrawLine {
                line: Line {
                    points: vec![
                        LinePoint {
                            p: Point::new(Mm(from_x_mm), Mm(y_mm)),
                            bezier: false,
                        },
                        LinePoint {
                            p: Point::new(Mm(to_x_mm), Mm(y_mm)),
                            bezier: false,
                        },
                    ],
                    is_closed: false,
                },
            },
            Op::RestoreGraphicsState,
        ]);
    }

    fn into_pages(mut self, certificate_id: &str) -> Vec<PdfPage> {
        let page_count = self.pages.len();
        let certificate_id_label = self.label("Certificate ID");
        let page_label = self.label("Page");
        for (index, ops) in self.pages.iter_mut().enumerate() {
            append_rule(ops, LEFT_MM, RIGHT_MM, FOOTER_RULE_Y_MM, 0.35);
            append_text(
                ops,
                LEFT_MM,
                FOOTER_TEXT_Y_MM,
                &format!("{certificate_id_label}: {certificate_id}"),
                5.8,
                BuiltinFont::Helvetica,
            );
            append_text(
                ops,
                166.0,
                FOOTER_TEXT_Y_MM,
                &format!("{page_label} {} / {page_count}", index + 1),
                6.5,
                BuiltinFont::Helvetica,
            );
        }
        self.pages
            .into_iter()
            .map(|ops| PdfPage::new(Mm(PAGE_WIDTH_MM), Mm(PAGE_HEIGHT_MM), ops))
            .collect()
    }
}

