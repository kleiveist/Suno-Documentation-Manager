fn validate_win_ansi(label: &str, value: &str) -> Result<()> {
    if let Some(character) = value.chars().find(|character| !is_win_ansi(*character)) {
        return Err(AppError::Data(format!(
            "Certificate PDF {label} contains a character unsupported by the built-in PDF fonts: U+{:04X}.",
            character as u32
        )));
    }
    Ok(())
}

fn is_win_ansi(character: char) -> bool {
    if character == '\n' {
        return true;
    }
    match character as u32 {
        0x20..=0x7e | 0xa0..=0xff => true,
        _ => matches!(
            character,
            '\u{20ac}'
                | '\u{201a}'
                | '\u{0192}'
                | '\u{201e}'
                | '\u{2026}'
                | '\u{2020}'
                | '\u{2021}'
                | '\u{02c6}'
                | '\u{2030}'
                | '\u{0160}'
                | '\u{2039}'
                | '\u{0152}'
                | '\u{017d}'
                | '\u{2018}'
                | '\u{2019}'
                | '\u{201c}'
                | '\u{201d}'
                | '\u{2022}'
                | '\u{2013}'
                | '\u{2014}'
                | '\u{02dc}'
                | '\u{2122}'
                | '\u{0161}'
                | '\u{203a}'
                | '\u{0153}'
                | '\u{017e}'
                | '\u{0178}'
        ),
    }
}

fn render_document_title(layout: &mut PdfLayout) {
    layout.write_wrapped(
        DOCUMENT_TITLE,
        LEFT_MM,
        RIGHT_MM - LEFT_MM,
        14.0,
        BuiltinFont::HelveticaBold,
        1.28,
    );
    layout.write_wrapped(
        "Finalisierter technischer Snapshot – keine rechtliche Zertifizierung",
        LEFT_MM,
        RIGHT_MM - LEFT_MM,
        7.5,
        BuiltinFont::Helvetica,
        1.2,
    );
    layout.y_mm -= 1.0;
    layout.rule(LEFT_MM, RIGHT_MM, layout.y_mm, 0.6);
    layout.y_mm -= 3.0;
}

