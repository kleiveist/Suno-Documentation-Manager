pub(super) fn artwork_answer(origin: &str, answer: Option<bool>) -> &'static str {
    if origin == "none" {
        "N/A"
    } else if origin.trim().is_empty() {
        "NOT DOCUMENTED"
    } else {
        yes_no(answer)
    }
}

pub(super) fn artwork_note_table_row(
    label: impl Into<String>,
    origin: &str,
    answer: Option<bool>,
    note: &str,
) -> TableRow {
    if origin == "none" {
        TableRow::system_plain(label, "N/A")
    } else if origin.trim().is_empty() {
        TableRow::system_plain(label, "NOT DOCUMENTED")
    } else {
        match answer {
            Some(true) => TableRow::documented_plain(label, note),
            Some(false) => TableRow::system_plain(label, "N/A"),
            None => TableRow::system_plain(label, "NOT DOCUMENTED"),
        }
    }
}

pub(super) fn branch_value(answer: Option<bool>, value: &str) -> &str {
    match answer {
        Some(true) => documented(value),
        Some(false) => "N/A",
        None => "NOT DOCUMENTED",
    }
}

