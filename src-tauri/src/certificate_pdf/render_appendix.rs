pub(super) fn render_integrity_anchors(
    layout: &mut PdfLayout,
    snapshot: &CertificatePdfSnapshot<'_>,
) {
    layout.section_title("K. Integrity anchors");
    let release_wav =
        evidence_digest(snapshot.evidence, EvidenceRole::ReleaseWav).unwrap_or("NOT DOCUMENTED");
    let final_artwork =
        evidence_digest(snapshot.evidence, EvidenceRole::FinalArtwork).unwrap_or("N/A");
    let open_blocking_deviations = snapshot
        .deviations
        .iter()
        .filter(|deviation| deviation.blocking && !deviation.resolved)
        .count();
    let revision_count_label = layout.label("Previous revision count [System verification]");
    layout.write_wrapped(
        &format!(
            "{revision_count_label}: {}",
            snapshot.revision_references.len()
        ),
        LEFT_MM,
        RIGHT_MM - LEFT_MM,
        7.2,
        BuiltinFont::HelveticaBold,
        1.3,
    );
    let rows = vec![
        TableRow::mono("Evidence file count", snapshot.evidence.len().to_string()),
        TableRow::mono("Release WAV SHA-256", release_wav),
        TableRow::mono("Final artwork SHA-256", final_artwork),
        TableRow::mono("SHA256SUMS.txt SHA-256", snapshot.sha256sums_sha256),
        TableRow::mono(
            "EVIDENCE_MANIFEST.json SHA-256",
            snapshot.evidence_manifest_sha256,
        ),
        TableRow::mono(
            "DOCUMENTATION_CERTIFICATE.md SHA-256",
            snapshot.markdown_certificate_sha256,
        ),
        TableRow::plain("Blocking deviations", open_blocking_deviations.to_string()),
        TableRow::mono("Certificate ID", snapshot.certificate_id),
        TableRow::mono("Finalization timestamp", snapshot.finalized_at),
        TableRow::system_mono(
            "Previous revision archives [System verification]",
            if snapshot.revision_references.is_empty() {
                "NONE RECORDED"
            } else {
                "Full numbered list in Technical Appendix"
            },
        ),
        TableRow::system_plain("Final result", "DOCUMENTATION COMPLETE"),
    ];
    layout.table_rows(&rows, 54.0);
}

